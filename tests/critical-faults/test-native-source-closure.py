#!/usr/bin/env python3
"""Prevent selecting legacy OpenWISP owners in the native OpenWiFi source."""
from pathlib import Path
import argparse,re
p=argparse.ArgumentParser();p.add_argument('--repo',type=Path,required=True);a=p.parse_args();r=a.repo
legacy=('cambium-openwisp-led','openwisp-config','openwisp-monitoring')
selected=[]
for f in (r/'profiles').rglob('*'):
 if not f.is_file() or f.suffix not in ('.yml','.yaml','.config'):continue
 for n in legacy:
  if re.search(r'^\s*-\s*'+re.escape(n)+r'(?:\s|$)',f.read_text(),re.M) or re.search(r'^CONFIG_PACKAGE_'+re.escape(n)+r'=y$',f.read_text(),re.M):selected.append(str(f)+':'+n)
assert not selected,selected
services=[str(f) for f in (r/'feeds/ucentral').rglob('*') if f.is_file() and 'init.d' in f.parts and 'openwisp' in f.name.lower()]
assert not services,services
for family in ('gambit','sage','jaguar','cheetah','thor','miami'):
 # Hardware support is generated by native platform patches; no legacy package is shipped here.
 assert not (r/'package/cambium/cambium-openwisp-led').exists()
state=(r/'feeds/ucentral/ucentral-state/files/ucentral-state').read_text()
assert "ubus.call('ucentral', 'status')" in state and 'controller_connected' in state
collector=(r/'feeds/ucentral/ucentral-state/files/ucentral-faults').read_text()
assert 'openwisp' not in collector.lower() and '/controller/checksum' not in collector
assert 'NL80211_CMD_TRIGGER_SCAN' not in collector and 'NL80211_CMD_GET_INTERFACE' in collector
print('PASS native source closure: no selected legacy OpenWISP services; existing authenticated connection and read-only radio dump retained')
